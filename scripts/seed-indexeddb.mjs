/**
 * Generates a real, temporary IndexedDB database for testing.
 *
 * Launches headless Chromium, drives it through the DevTools Protocol, and writes the
 * seed dataset into a genuine IndexedDB using the same schema constants the shipped
 * app reads from `src/config/database.ts`. Every record is read back and verified
 * before the run is reported as successful.
 *
 * Artifacts written to `.testdata/`:
 *   afritecx_badboy_pos.idb.json    inspectable summary of what was stored
 *   afritecx_badboy_pos.leveldb/    the Chromium LevelDB holding the database
 *
 * Usage:  npm run build && npm run db:seed
 */

import { build } from 'esbuild';
import { mkdir, rm, writeFile, cp, readdir } from 'node:fs/promises';
import { existsSync, createReadStream } from 'node:fs';
import { join, resolve, extname } from 'node:path';
import { spawn } from 'node:child_process';
import http from 'node:http';

const ROOT = resolve('.');
const DIST = join(ROOT, 'dist');
const OUT = join(ROOT, '.testdata');
const PROFILE = join(OUT, 'profile');
const SITE_PORT = 4319;
const CDP_PORT = 9321;

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};

const CHROMIUM = process.env.CHROMIUM_PATH || '/usr/bin/chromium';

if (!existsSync(join(DIST, 'index.html'))) {
  console.error('dist/index.html not found. Run `npm run build` first.');
  process.exit(1);
}
if (!existsSync(CHROMIUM)) {
  console.error(`Chromium not found at ${CHROMIUM}. Set CHROMIUM_PATH to override.`);
  process.exit(1);
}

await rm(OUT, { recursive: true, force: true });
await mkdir(PROFILE, { recursive: true });

/* ── 1. Build the seeding routine from the real app modules ─────────────────── */

const entry = join(OUT, 'seed-entry.ts');
await writeFile(entry, `
import { initialProducts, initialCustomers, initialTransactions, initialAccounts,
         initialJournalEntries, initialShifts, initialEmployees, initialPayrollRuns,
         SEED_USERS } from ${JSON.stringify(join(ROOT, 'src/data/seed.ts'))};
import { DEFAULT_BUSINESS_PROFILE } from ${JSON.stringify(join(ROOT, 'src/utils/industryPresets.ts'))};
import { LOCAL_STORE_CONFIG } from ${JSON.stringify(join(ROOT, 'src/config/database.ts'))};

const payload = {
  products: initialProducts,
  customers: initialCustomers,
  transactions: initialTransactions,
  accounts: initialAccounts,
  journalEntries: initialJournalEntries,
  shifts: initialShifts,
  employees: initialEmployees,
  payrollRuns: initialPayrollRuns,
  users: SEED_USERS,
  businessProfile: DEFAULT_BUSINESS_PROFILE,
  snapshots: [],
};

const NAME = LOCAL_STORE_CONFIG.databaseName;
const VERSION = LOCAL_STORE_CONFIG.version;

const openDb = () => new Promise((res, rej) => {
  const req = indexedDB.open(NAME, VERSION);
  req.onupgradeneeded = () => {
    const db = req.result;
    if (!db.objectStoreNames.contains('appState')) db.createObjectStore('appState', { keyPath: 'key' });
    if (!db.objectStoreNames.contains('auditLog')) {
      const audit = db.createObjectStore('auditLog', { keyPath: 'id' });
      audit.createIndex('at', 'at', { unique: false });
    }
  };
  req.onsuccess = () => res(req.result);
  req.onerror = () => rej(req.error);
});

const run = (db, store, mode, fn) => new Promise((res, rej) => {
  const tx = db.transaction(store, mode);
  const req = fn(tx.objectStore(store));
  req.onsuccess = () => res(req.result);
  req.onerror = () => rej(req.error);
  tx.onerror = () => rej(tx.error);
});

// Wrapped in an async IIFE: the bundle is injected as a classic script, which
// cannot use top-level await.
globalThis.__SEED__ = null;
globalThis.__SEED_PAYLOAD__ = payload;
globalThis.__SEED_PROMISE__ = (async () => {
const db = await openDb();
await run(db, 'appState', 'readwrite', store => store.put({
  key: 'state', version: VERSION, updatedAt: new Date().toISOString(), data: payload,
}));
await run(db, 'auditLog', 'readwrite', store => store.add({
  id: 'seed-' + Date.now(), at: new Date().toISOString(),
  action: 'seed', detail: 'Temporary test dataset generated by scripts/seed-indexeddb.mjs',
}));

// Read back through fresh transactions to prove the write persisted.
const stored = await run(db, 'appState', 'readonly', store => store.get('state'));
const auditCount = await run(db, 'auditLog', 'readonly', store => store.count());
db.close();

return {
  databaseName: NAME,
  version: VERSION,
  storeNames: ['appState', 'auditLog'],
  recordCounts: Object.fromEntries(Object.entries(payload).map(([k, v]) => [k, Array.isArray(v) ? v.length : 1])),
  totalRecords: Object.values(payload).reduce((n, v) => n + (Array.isArray(v) ? v.length : 0), 0),
  auditCount,
  readBackOk: !!stored && stored.data.products.length === payload.products.length,
  trialBalanceBalanced: (() => {
    const debit = payload.accounts.filter(a => a.type === 'asset' || a.type === 'expense').reduce((s, a) => s + a.balance, 0);
    const credit = payload.accounts.filter(a => a.type === 'liability' || a.type === 'equity' || a.type === 'revenue').reduce((s, a) => s + a.balance, 0);
    return Math.abs(debit - credit) < 0.01;
  })(),
  users: payload.users.map(u => ({ username: u.username, role: u.role, hashed: !!u.passwordHash })),
  payload,
};
})();
`);

const bundle = join(OUT, 'seed-bundle.js');
await build({
  entryPoints: [entry],
  outfile: bundle,
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'chrome120',
  logLevel: 'error',
  // `src/config/database.ts` reads `import.meta.env`, which does not exist in an
  // IIFE bundle. Vite normally substitutes it; esbuild needs to be told to.
  define: {
    'import.meta.env': JSON.stringify({
      VITE_IDB_NAME: process.env.VITE_IDB_NAME || 'afritecx_badboy_pos',
      VITE_IDB_VERSION: process.env.VITE_IDB_VERSION || '1',
    }),
  },
});

/* ── 2. Serve dist/ so IndexedDB gets a real HTTP origin ────────────────────── */

await cp(bundle, join(DIST, '__seed-bundle.js'));
await writeFile(join(DIST, '__seed.html'), '<!doctype html><meta charset="utf-8"><title>seed</title>');

const server = http.createServer((req, res) => {
  const urlPath = decodeURIComponent((req.url || '/').split('?')[0]);
  const file = join(DIST, urlPath === '/' ? 'index.html' : urlPath);
  if (!existsSync(file)) { res.writeHead(404); res.end('not found'); return; }
  res.writeHead(200, { 'content-type': MIME[extname(file)] ?? 'application/octet-stream' });
  createReadStream(file).pipe(res);
});
await new Promise(r => server.listen(SITE_PORT, '127.0.0.1', r));

/* ── 3. Drive Chromium over CDP ────────────────────────────────────────────── */

const chrome = spawn(CHROMIUM, [
  '--headless=new',
  '--no-sandbox',
  '--disable-gpu',
  '--disable-dev-shm-usage',
  '--disable-extensions',
  `--remote-debugging-port=${CDP_PORT}`,
  `--user-data-dir=${PROFILE}`,
  'about:blank',
], { stdio: 'ignore' });

const httpJson = path => new Promise((res, rej) => {
  http.get({ host: '127.0.0.1', port: CDP_PORT, path }, r => {
    let body = '';
    r.on('data', c => { body += c; });
    r.on('end', () => { try { res(JSON.parse(body)); } catch (e) { rej(e); } });
  }).on('error', rej);
});

let target = null;
for (let attempt = 0; attempt < 80 && !target; attempt++) {
  try {
    const list = await httpJson('/json/list');
    target = list.find(t => t.type === 'page');
  } catch { /* browser still starting */ }
  if (!target) await new Promise(r => setTimeout(r, 250));
}
if (!target) {
  server.close();
  chrome.kill();
  console.error('Could not attach to Chromium.');
  process.exit(1);
}

const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((res, rej) => {
  ws.onopen = res;
  ws.onerror = () => rej(new Error('CDP socket failed'));
});

let messageId = 0;
const waiting = new Map();
ws.onmessage = event => {
  const msg = JSON.parse(event.data);
  if (msg.id && waiting.has(msg.id)) {
    waiting.get(msg.id)(msg);
    waiting.delete(msg.id);
  }
};
const send = (method, params = {}) => new Promise(res => {
  const id = ++messageId;
  waiting.set(id, res);
  ws.send(JSON.stringify({ id, method, params }));
});

await send('Page.navigate', { url: `http://127.0.0.1:${SITE_PORT}/__seed.html` });
await new Promise(r => setTimeout(r, 1200));

const injected = await send('Runtime.evaluate', {
  expression: `(async () => {
    try {
      await new Promise((res, rej) => {
        const s = document.createElement('script');
        s.src = '/__seed-bundle.js';
        s.onload = res;
        s.onerror = () => rej(new Error('seed bundle failed to load'));
        document.head.appendChild(s);
      });
      if (!globalThis.__SEED_PROMISE__) return 'ERROR: bundle loaded but __SEED_PROMISE__ missing';
      const r = await globalThis.__SEED_PROMISE__;
    return JSON.stringify(r);
    } catch (e) {
      return 'ERROR: ' + (e && e.stack ? e.stack : String(e));
    }
  })()`,
  awaitPromise: true,
  returnByValue: true,
  userGesture: true,
});

ws.close();
chrome.kill();
server.close();
// Chromium holds file handles on its profile for a moment after SIGTERM; wait for
// the process to exit before touching the directory, otherwise cleanup races it.
await new Promise(res => {
  const done = () => res();
  chrome.once('exit', done);
  setTimeout(() => { try { chrome.kill('SIGKILL'); } catch {} done(); }, 8000);
});

const raw = injected.result?.result?.value;
if (!raw) {
  console.error('Seeding failed: the browser returned no result.');
  console.error(JSON.stringify(injected, null, 2));
  process.exit(1);
}
const result = JSON.parse(raw);

await rm(join(DIST, '__seed.html'), { force: true });
await rm(join(DIST, '__seed-bundle.js'), { force: true });

if (!result.readBackOk) {
  console.error('Seeding failed: the IndexedDB write did not read back correctly.');
  process.exit(1);
}

/* ── 4. Keep the LevelDB and write a readable summary ──────────────────────── */

const idbRoot = join(PROFILE, 'Default', 'IndexedDB');
let leveldbCopied = false;
if (existsSync(idbRoot)) {
  for (const entryName of await readdir(idbRoot)) {
    if (entryName.startsWith('http_127.0.0.1')) {
      await cp(join(idbRoot, entryName), join(OUT, 'afritecx_badboy_pos.leveldb'), { recursive: true });
      leveldbCopied = true;
      break;
    }
  }
}

// The LevelDB is bound to the seeding origin, so it cannot simply be dropped into
// the desktop profile (which uses app://pos.local). A backup in the app's own
// format is the portable artifact: restore it through SQL DB & Backup.
await writeFile(
  join(OUT, 'afritecx_testdata_backup.json'),
  JSON.stringify(result.payload, null, 2) + '\n'
);

await writeFile(join(OUT, 'afritecx_badboy_pos.idb.json'), JSON.stringify({
  generatedAt: new Date().toISOString(),
  origin: `http://127.0.0.1:${SITE_PORT}`,
  database: { name: result.databaseName, version: result.version },
  stores: result.storeNames,
  totalRecords: result.totalRecords,
  recordCounts: result.recordCounts,
  auditRecords: result.auditCount,
  trialBalanceBalanced: result.trialBalanceBalanced,
  users: result.users,
  leveldbCopied,
}, null, 2) + '\n');

// Retry: Windows and Linux both occasionally keep a lock briefly after exit.
for (let attempt = 0; attempt < 10; attempt++) {
  try {
    await rm(PROFILE, { recursive: true, force: true });
    break;
  } catch {
    await new Promise(r => setTimeout(r, 400));
  }
}
await rm(entry, { force: true });
await rm(bundle, { force: true });

console.log(`IndexedDB seeded: ${result.databaseName} v${result.version}`);
console.log(`  stores             : ${result.storeNames.join(', ')}`);
console.log(`  total records      : ${result.totalRecords}`);
console.log(`  trial balance      : ${result.trialBalanceBalanced ? 'balanced' : 'OUT OF BALANCE'}`);
console.log(`  users hashed       : ${result.users.every(u => u.hashed) ? 'yes' : 'NO'}`);
console.log(`  read-back          : OK`);
console.log(`  artifacts          : .testdata/`);

if (!result.trialBalanceBalanced) process.exit(1);
