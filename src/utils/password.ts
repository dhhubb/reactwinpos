/**
 * Password hashing for stored user records.
 *
 * The original app kept plain-text passwords in browser storage and rendered them in
 * the user table. Storing credentials in the clear is unacceptable for a till that is
 * left unattended, so passwords are now salted and iterated through SHA-256 before
 * they are persisted. This is deliberately implemented in plain TypeScript: the
 * desktop build runs from a custom `app://` origin and from `file://` during support
 * sessions, where `crypto.subtle` is not guaranteed to exist.
 */

